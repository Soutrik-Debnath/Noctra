/**
 * Emits src/components/solid.ts — the solid-glyph bodies used for active/selected states.
 *
 * Provenance: Phosphor Icons (MIT), read out of @iconify-json/ph. Only the handful of names the app
 * actually renders are emitted, and only in the Fill weight. Phosphor draws on a 256 grid, so each
 * entry carries its own viewBox instead of the 24 grid the hand-authored set uses.
 *
 * The traced heart is deliberately NOT here. It lives in the `filled` map of icons.ts, so
 * Icon.svelte resolves a `<name>-filled` entry there first and this file only fills the gaps.
 *
 * Usage: node scripts/extract-solid-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(
  readFileSync(path.join(root, "node_modules/@iconify-json/ph/icons.json"), "utf8"),
);
const phVersion = JSON.parse(
  readFileSync(path.join(root, "node_modules/@iconify-json/ph/package.json"), "utf8"),
).version;

/** app icon name -> Phosphor Fill glyph */
const MAP = {
  home: "house-fill",
  library: "books-fill",
  stats: "chart-bar-fill",
  // `playlists` and `settings` are deliberately absent. Both are line-based glyphs, and every list
  // and slider concept in Phosphor is drawn inside a rounded panel, so their Fill weight changes the
  // object rather than its weight. Line glyphs get a heavier stroke instead — see Icon.svelte.
};

const entries = Object.entries(MAP).map(([name, phName]) => {
  const icon = pkg.icons[phName];
  if (!icon) throw new Error(`${phName} is not in the Phosphor set`);
  return { name, phName, body: icon.body };
});

const body = entries
  .map((e) => `  ${JSON.stringify(e.name)}: ${JSON.stringify(e.body)}, // ${e.phName}`)
  .join("\n");

const out = `/**
 * GENERATED by scripts/extract-solid-icons.mjs — do not edit by hand.
 *
 * Solid glyphs for active/selected states, extracted from Phosphor Icons ${phVersion} (MIT).
 * Phosphor's Bold weight is only a thicker outline, so it is useless for a "this is the current one"
 * signal; Fill is the weight that actually reads as solid at 19px.
 */
export const SOLID_VIEWBOX = "0 0 256 256";

export const solid: Record<string, string> = {
${body}
};
`;

writeFileSync(path.join(root, "src/components/solid.ts"), out);
console.log(`wrote src/components/solid.ts (${entries.length} glyphs)`);
